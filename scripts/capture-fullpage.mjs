import { writeFile } from 'node:fs/promises';
const [url, outputPath] = process.argv.slice(2);
if (!url || !outputPath) throw new Error('Usage: capture-fullpage.mjs <url> <output.png>');
const pages = await fetch('http://127.0.0.1:9223/json').then(response => response.json());
const page = pages.find(candidate => candidate.type === 'page');
if (!page) throw new Error('No Chrome target on port 9223.');
const socket = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((resolve, reject) => { socket.addEventListener('open', resolve, { once: true }); socket.addEventListener('error', reject, { once: true }); });
let sequence = 0;
const pending = new Map();
socket.addEventListener('message', event => { const message = JSON.parse(event.data); if (!message.id || !pending.has(message.id)) return; const callbacks = pending.get(message.id); pending.delete(message.id); if (message.error) callbacks.reject(new Error(message.error.message)); else callbacks.resolve(message.result); });
const send = (method, params = {}) => new Promise((resolve, reject) => { const id = ++sequence; pending.set(id, { resolve, reject }); socket.send(JSON.stringify({ id, method, params })); });
await send('Page.enable');
await send('Emulation.setDeviceMetricsOverride', { width: 1600, height: 900, deviceScaleFactor: 1, mobile: false, screenWidth: 1600, screenHeight: 900 });
await send('Page.navigate', { url });
await new Promise(resolve => setTimeout(resolve, 1800));
const metrics = await send('Page.getLayoutMetrics');
const width = Math.ceil(metrics.cssContentSize.width);
const height = Math.ceil(metrics.cssContentSize.height);
const screenshot = await send('Page.captureScreenshot', { format: 'png', fromSurface: true, captureBeyondViewport: true, clip: { x: 0, y: 0, width, height, scale: 1 } });
await writeFile(outputPath, Buffer.from(screenshot.data, 'base64'));
socket.close();
process.stdout.write(`Captured ${width}x${height} contact sheet.\n`);
